def scene_plan_schema(user_prompt: str) -> dict[str, Any]:
    schema = copy.deepcopy(SCENE_PLAN_SCHEMA)
    fragments = required_source_fragments(user_prompt)
    trace = schema["properties"]["source_trace"]
    trace["minItems"] = len(fragments)
    trace["maxItems"] = len(fragments)
    trace["items"]["properties"]["detail"]["enum"] = fragments
    return schema


def _placeholder_scene_text(value: Any) -> bool:
    text = str(value or "").strip().casefold().strip(" .,:;-_")
    return text in {"", "none", "n/a", "na", "not applicable", "no interaction", "no behavior", "no animation"}


def _malformed_trace_text(value: Any) -> bool:
    text = str(value or "").strip()
    return _placeholder_scene_text(text) or len(text.split()) < 5 or any(token in text for token in ("{", "}", "[", "]", "id:"))


def _aabb_overlap(center_a: list[float], half_a: list[float], center_b: list[float], half_b: list[float]) -> bool:
    return all(abs(center_a[index] - center_b[index]) < half_a[index] + half_b[index] for index in range(3))


def _distance3(a: list[float], b: list[float]) -> float:
    return sum((a[index] - b[index]) ** 2 for index in range(3)) ** 0.5


