def _is_meta_fragment(fragment: str) -> bool:
    value = _compact(fragment).casefold().rstrip(".!?")
    return any(re.fullmatch(pattern, value) for pattern in META_FRAGMENT_PATTERNS)


def _detail_stem(token: str) -> str:
    value = token.casefold()
    if value in DETAIL_CANONICAL:
        return DETAIL_CANONICAL[value]
    if value.endswith("ies") and len(value) > 5:
        value = value[:-3] + "y"
    elif value.endswith("ing") and len(value) > 6:
        value = value[:-3]
        if value.endswith(value[-1:] * 2):
            value = value[:-1]
    elif value.endswith("ed") and len(value) > 5:
        value = value[:-2]
    elif value.endswith("es") and len(value) > 5:
        value = value[:-2]
    elif value.endswith("s") and len(value) > 4:
        value = value[:-1]
    return DETAIL_CANONICAL.get(value, value)


def _detail_terms(text: str) -> set[str]:
    raw = re.findall(r"\d+(?:\.\d+)?(?::\d+)?|[a-zA-Z]+", text.casefold())
    terms: set[str] = set()
    for token in raw:
        stem = _detail_stem(token)
        if stem in DETAIL_STOPWORDS or len(stem) < 2:
            continue
        terms.add(stem)
    return terms


def detail_preservation_errors(output: str, user_prompt: str, context: str) -> list[str]:
    output_terms = _detail_terms(output)
    errors: list[str] = []
    for fragment in required_source_fragments(user_prompt):
        required = _detail_terms(fragment)
        missing = sorted(required - output_terms)
        if missing:
            errors.append(f"{context} omitted concrete detail terms {missing!r} from {fragment!r}")
    for literal in _numeric_literals(user_prompt):
        if literal not in output:
            errors.append(f"{context} omitted numeric user detail {literal!r}")
    return errors


def required_source_fragments(user_prompt: str) -> list[str]:
    source = _compact(user_prompt)
    if not source:
        return ["(empty user description)"]
    if len(source) <= 96:
        return [source]
    pieces = re.split(
        r"(?:[\n;]+|(?<=[.!?])\s+|\s*,\s*|\s+\b(?:and|but|while|including|with)\b\s+)",
        source,
        flags=re.I,
    )
    fragments: list[str] = []
    for raw in pieces:
        value = raw.strip(" \t\r\n,;:.!?\"")
        value = re.sub(r"^(?:and|but|while|including|with)\s+", "", value, flags=re.I)
        if len(value) < 3:
            continue
        if len(value) > 180:
            words = value.split()
            for index in range(0, len(words), 24):
                chunk = " ".join(words[index:index + 24]).strip()
                if len(chunk) >= 3:
                    fragments.append(chunk)
        else:
            fragments.append(value)
    for quoted in re.findall(r"[\"“](.*?)[\"”]", source):
        value = quoted.strip()
        if len(value) >= 2:
            fragments.append(value)
    unique: list[str] = []
    seen: set[str] = set()
    for fragment in fragments:
        if _is_meta_fragment(fragment):
            continue
        key = fragment.casefold()
        if key not in seen:
            seen.add(key)
            unique.append(fragment)
    return unique[:16] or ([source] if not _is_meta_fragment(source) else ["game concept"])


def explicit_title_hint(user_prompt: str) -> str | None:
    source = _compact(user_prompt)
    words = source.split()
    if not 1 <= len(words) <= 6 or re.search(r"[.!?;:]", source):
        return None
    letters = [word for word in words if any(ch.isalpha() for ch in word)]
    if not letters or not all(word[0].isupper() for word in letters):
        return None
    return source


def canonicalize_authored_text(text: str) -> str:
    markers = [
        "TITLE", "GAME CATEGORY", "COMPLETE GAME DESCRIPTION", "CORE GAMEPLAY LOOP",
        "SOURCE FIDELITY", "OPENING SCENE", "PLAYER START", "ENVIRONMENT DESCRIPTION",
        "IMMEDIATE SITUATION", "LANDMARKS AND EXITS", "SOURCE DETAILS IN SCENE",
    ]
    output: list[str] = []
    for line in text.strip().splitlines():
        cleaned = line.strip()
        cleaned = re.sub(r"^#{1,6}\s*", "", cleaned)
        cleaned = cleaned.replace("**", "").replace("__", "")
        upper = cleaned.upper()
        matched = False
        for marker in markers:
            if upper == marker or upper == marker + ":":
                output.append(marker + ":")
                matched = True
                break
            if upper.startswith(marker + ":"):
                output.append(marker + ":" + cleaned[len(marker) + 1:])
                matched = True
                break
        if matched:
            continue
        if upper in {"END GAME DESCRIPTION", "END OPENING SCENE"}:
            output.append(upper)
        else:
            output.append(line.rstrip())
    return "\n".join(output).strip()


def extract_title(game_description: str) -> str:
    match = re.search(r"(?im)^TITLE\s*:\s*(.+?)\s*$", game_description)
    if match:
        return match.group(1).strip()
    for line in game_description.splitlines():
        value = re.sub(r"^#{1,6}\s*", "", line.strip())
        value = value.replace("**", "").replace("__", "").strip()
        if value:
            return value[:120]
    return ""


def extract_category(game_description: str) -> str:
    match = re.search(r"(?im)^(?:GAME CATEGORY|CATEGORY|GENRE)\s*:\s*(.+?)\s*$", game_description)
    return match.group(1).strip() if match else ""


def _numeric_literals(text: str) -> list[str]:
    return list(dict.fromkeys(re.findall(r"\b\d+(?:\.\d+)?\b", text)))


def _refusal_error(text: str) -> str | None:
    opening = text[:500].casefold()
    patterns = (
        "i can't help", "i cannot help", "i'm unable to", "i am unable to",
        "as an ai", "cannot comply", "can't comply", "cannot fulfill",
    )
    return next((phrase for phrase in patterns if phrase in opening), None)


def _contains_cjk(text: str) -> bool:
    return any("\u3400" <= char <= "\u9fff" for char in text)


def _degenerate_repetition(text: str) -> bool:
    words = re.findall(r"[a-z0-9']+", text.casefold())
    if len(words) < 80:
        return False
    trigrams = [tuple(words[index:index + 3]) for index in range(len(words) - 2)]
    return bool(trigrams) and len(set(trigrams)) < len(trigrams) * 0.45


def _has_complete_ending(text: str) -> bool:
    stripped = text.rstrip().rstrip("*_#` ").rstrip()
    return bool(stripped) and stripped.endswith((".", "!", "?", '"', "'", "”", "’"))


def validate_game_description(text: str, user_prompt: str) -> list[str]:
    errors: list[str] = []
    stripped = text.strip()
    if len(stripped) < 750:
        errors.append("game description is too short to define a complete game")
    if len(stripped) > 12000:
        errors.append("game description exceeds the authored-prose budget")
    if not _has_complete_ending(stripped):
        errors.append("game description appears incomplete or truncated")
    title = extract_title(stripped)
    if not title:
        errors.append("game title is missing from the first nonempty line")
    title_hint = explicit_title_hint(user_prompt)
    if title_hint is not None and title != title_hint:
        errors.append("title-like user input was not preserved as the exact first-line title")
    errors.extend(detail_preservation_errors(stripped, user_prompt, "game description"))
    refusal = _refusal_error(stripped)
    if refusal:
        errors.append(f"model refused creative source material using {refusal!r}")
    if _contains_cjk(stripped):
        errors.append("game description switched away from English")
    if _degenerate_repetition(stripped):
        errors.append("game description contains a degenerate repetition loop")
    return errors


