"""Compute exact word-count and character-count covers for the shipped dictionaries.
Requires numpy and scipy. Run from the typewriter project directory.
"""
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path
import json
import os
import re
import warnings

os.environ["OPENBLAS_NUM_THREADS"] = "1"
os.environ["OMP_NUM_THREADS"] = "1"
import numpy as np
from scipy.optimize import Bounds, LinearConstraint, milp
from scipy.sparse import csc_matrix

ROOT = Path(__file__).resolve().parents[1]


def solve(job):
    level, lang, keys, vocabulary = job
    letters = set(keys)
    choices = {}
    for w in vocabulary:
        mask = frozenset(w)
        if mask <= letters and (mask not in choices or len(w) < len(choices[mask])):
            choices[mask] = w
    if not choices:
        return level, lang, [[], []]
    words = list(choices.values())
    rows = sorted(set().union(*choices))
    cover = csc_matrix([[int(k in w) for w in words] for k in rows])
    constraints = LinearConstraint(cover, 1, np.inf)
    costs = np.array([len(w) + 1 for w in words], dtype=float)
    def optimum(objective):
        with warnings.catch_warnings():
            warnings.filterwarnings("ignore", message="Unrecognized options")
            answer = milp(objective, integrality=np.ones(len(words)), bounds=Bounds(0,1),
                          constraints=constraints, options={"mip_rel_gap": 0, "threads": 1})
        if not answer.success:
            raise RuntimeError((lang, level, answer.message))
        return [word for word, used in zip(words, answer.x) if used > 0.5]
    # One extra word must cost more than any possible savings in spelling.
    fewest = optimum(costs + (len(rows) * max(costs) + 1))
    shortest = optimum(costs)
    print(level, lang, len(fewest), sum(map(len, shortest))+len(shortest)-1, flush=True)
    return level, lang, [fewest, shortest]


if __name__ == "__main__":
    order = re.search(r"Array.from\('([a-zäöü]+)'\)", (ROOT/"src/training_text.js").read_text())[1]
    banks = {}
    for lang in ["de", "en"]:
        words = []
        for tier in re.findall(r"`([^`]*)`", (ROOT/f"vocabulary/{lang}.js").read_text()):
            previous = ""
            for prefix, suffix in re.findall(r"(\d+)([a-zäöü]+)", tier):
                previous = previous[:int(prefix)] + suffix
                words.append(previous)
        banks[lang] = words
    banks["mixed"] = sorted(set(banks["de"] + banks["en"]))
    result = {lang:[None]*28 for lang in banks}
    jobs = [(n,lang,order[:n+1],words) for n in range(1,29) for lang,words in banks.items()]
    with ProcessPoolExecutor(max_workers=3) as workers:
        for n,lang,solutions in workers.map(solve,jobs):
            result[lang][n-1] = solutions
    data = json.dumps(result,ensure_ascii=False,separators=(",",":"))
    (ROOT/"vocabulary/covers.js").write_text("// Generated by tools/build_covers.py\nexport default "+data+";\n")
